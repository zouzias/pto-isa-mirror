from gen_isa_svg_core import CANVAS_W, DEFAULT_OUTPUT_DIR

PURPLE = "#6A47C4"
TEAL = "#087F8C"
BLOCK_COLORS = ["#EDE7FF", "#DDF4F2", "#FFF0DD", "#E8EDFF", "#F5E3F0"]


class MemoryLayoutFigure:
    def __init__(self, name: str, title: str, subtitle: str, height: int, description: str):
        self.name = name
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS_W}" height="{height}" '
            f'viewBox="0 0 {CANVAS_W} {height}" role="img" aria-labelledby="title desc">',
            "<!-- Generated by docs/tools/gen_memory_layout_svgs.py. -->",
            f'<title id="title">{escape(title)}</title>',
            f'<desc id="desc">{escape(description)}</desc>',
            '<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" '
            'orient="auto-start-reverse"><path d="M0,0 L8,4 L0,8 Z" fill="#64748b"/></marker></defs>',
            "<style>text { font-family: Arial, Helvetica, sans-serif; fill: #0f172a; } "
            ".title { font-size: 30px; font-weight: 700; } "
            ".heading { font-size: 21px; font-weight: 700; } .body { font-size: 18px; } "
            ".small { font-size: 16px; fill: #334155; } "
            ".mono { font-family: monospace; font-size: 18px; }</style>",
        ]
        self.add_rect(0, 0, CANVAS_W, height, "#FFFFFF", "none", 0)
        self.add_text(36, 46, title, "title")
        self.add_text(36, 80, subtitle)

    def add_rect(
        self,
        x: float,
        y: float,
        width: float,
        height: float,
        fill: str = "#F8FAFC",
        stroke: str = "#CBD5E1",
        radius: int = 10,
    ) -> None:
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="{radius}" '
            f'fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>'
        )

    def add_text(self, x: float, y: float, text: str, css_class: str = "body", anchor: str = "start") -> None:
        self.parts.append(f'<text x="{x}" y="{y}" class="{css_class}" text-anchor="{anchor}">{escape(text)}</text>')

    def add_line(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        arrow_end: bool = False,
        arrow_start: bool = False,
        color: str = "#64748b",
        dash: Optional[str] = None,
    ) -> None:
        attributes = ' marker-end="url(#arrow)"' if arrow_end else ""
        if arrow_start:
            attributes += ' marker-start="url(#arrow)"'
        if dash:
            attributes += f' stroke-dasharray="{dash}"'
        self.parts.append(
            f'<path d="M{x1},{y1} L{x2},{y2}" fill="none" stroke="{color}" stroke-width="2"{attributes}/>'
        )

    def render(self) -> str:
        return "\n".join([*self.parts, "</svg>"]) + "\n"


