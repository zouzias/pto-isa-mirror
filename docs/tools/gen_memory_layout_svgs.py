def main() -> int:
    parser = argparse.ArgumentParser(description="Generate detailed memory-layout SVG diagrams")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--check", action="store_true", help="Check that generated SVGs match the tracked files")
    args = parser.parse_args()
    figures = [
        _render_tload_stride_fallback(),
        _render_tinsert_nz_split(),
        _render_textract_nd2nz_windows(),
        _render_textract_acc_nz_groups(),
    ]
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    errors = []
    for figure in figures:
        path = args.output_dir / f"{figure.name}.svg"
        expected = figure.render()
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                errors.append(f"missing or out-of-date SVG: {path}")
        else:
            path.write_text(expected, encoding="utf-8")
    if errors:
        for error in errors:
            print(f"ERROR: {error}")
        return 1
    print(f"OK: {len(figures)} memory-layout SVGs {'match their source' if args.check else 'generated'}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
